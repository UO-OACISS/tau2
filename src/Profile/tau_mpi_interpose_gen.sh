#!/bin/sh
# usage: tau_mpi_interpose_gen.sh header|source <MPI wrapper objects>
#
# On macOS, a library inserted with DYLD_INSERT_LIBRARIES replaces the MPI
# library's functions only through __DATA,__interpose entries. Furthermore,
# the replacement function must be  defined in the inserted library.
# This script generates 

mode=$1
shift

syms=`nm -gU "$@" | awk 'NF == 3 && $2 == "T" && tolower($3) ~ /^_mpi_/ { print substr($3, 2) }' | sort -u`

case $mode in
header)
  echo "/* Generated by tau_mpi_interpose_gen.sh */"
  for s in $syms; do
    echo "#define $s tau_ip_$s"
  done
  ;;
source)
  echo "/* Generated by tau_mpi_interpose_gen.sh */"
  for s in $syms; do
    echo "extern char tau_ip_$s;"
    # Use weak_import so that a wrapper for a function not present
    # in the MPI library is skipped.
    echo "extern char $s __attribute__((weak_import));"
  done
  echo "__attribute__((used)) static const struct { const void * replacement; const void * replacee; }"
  echo "tau_mpi_interpose[] __attribute__((section(\"__DATA,__interpose\"))) = {"
  for s in $syms; do
    echo "  { &tau_ip_$s, &$s },"
  done
  echo "};"
  ;;
*)
  echo "usage: $0 header|source <objects>" >&2
  exit 1
  ;;
esac
